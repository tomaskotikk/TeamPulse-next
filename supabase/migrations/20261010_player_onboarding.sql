-- Player onboarding + parent accounts
-- Additive only: creates new tables, does not modify existing ones.
begin;

-- Player application (staging until accounts are activated)
create table if not exists public.player_applications (
  id bigint generated by default as identity primary key,
  club_id bigint not null references public.clubs(id) on delete cascade,
  invitation_id bigint references public.team_invitations(id) on delete set null,
  email varchar(255) not null,
  password_hash varchar(255) not null,
  first_name varchar(100) not null,
  last_name varchar(100) not null,
  date_birth date not null,
  phone varchar(30),
  street varchar(255) not null,
  city varchar(120) not null,
  zip varchar(10) not null,
  health_insurance varchar(120) not null,
  health_notes text,
  emergency_name varchar(200),
  emergency_phone varchar(30),
  parent_first_name varchar(100),
  parent_last_name varchar(100),
  parent_email varchar(255),
  parent_phone varchar(30),
  consent_gdpr boolean not null check (consent_gdpr = true),
  consent_photos boolean not null default false,
  status varchar(20) not null default 'pending_manager'
    check (status in ('pending_manager', 'pending_parent', 'completed', 'rejected')),
  rejection_reason text,
  reviewed_by bigint references public.users(id) on delete set null,
  reviewed_at timestamptz,
  player_user_id bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_player_applications_club_status
  on public.player_applications(club_id, status);
create index if not exists idx_player_applications_email
  on public.player_applications(lower(email));
create index if not exists idx_player_applications_parent_email
  on public.player_applications(lower(parent_email));

-- Parent registration invitations
create table if not exists public.parent_invitations (
  id bigint generated by default as identity primary key,
  token varchar(64) not null unique,
  application_id bigint not null references public.player_applications(id) on delete cascade,
  email varchar(255) not null,
  expires_at timestamptz not null,
  used boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists idx_parent_invitations_application
  on public.parent_invitations(application_id);

-- Extended member profile (1:1 with users)
create table if not exists public.member_profiles (
  user_id bigint primary key references public.users(id) on delete cascade,
  street varchar(255),
  city varchar(120),
  zip varchar(10),
  health_insurance varchar(120),
  health_notes text,
  emergency_name varchar(200),
  emergency_phone varchar(30),
  consent_gdpr_at timestamptz,
  consent_photos boolean not null default false,
  updated_at timestamptz not null default now()
);

-- Parent ↔ child link (one parent can have multiple children)
create table if not exists public.parent_children (
  parent_user_id bigint not null references public.users(id) on delete cascade,
  child_user_id bigint not null references public.users(id) on delete cascade,
  club_id bigint not null references public.clubs(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (parent_user_id, child_user_id)
);

create index if not exists idx_parent_children_child
  on public.parent_children(child_user_id);

commit;
