-- Category walls: posts visible only to members of a category (plus club staff).
-- Additive only.
begin;

create table if not exists public.category_posts (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.club_categories(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  message text not null check (char_length(message) between 1 and 4000),
  created_at timestamptz not null default now()
);

create index if not exists idx_category_posts_category_created
  on public.category_posts(category_id, created_at desc);

-- realtime signal for the mobile app (same setup as chat_messages)
alter publication supabase_realtime add table public.category_posts;
alter table public.category_posts replica identity full;

commit;
