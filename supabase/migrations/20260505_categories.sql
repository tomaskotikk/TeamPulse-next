-- Club categories (age groups)
create table if not exists public.club_categories (
  id bigint generated by default as identity primary key,
  club_id bigint not null references public.clubs(id) on delete cascade,
  name varchar(60) not null,
  birth_year_from int,
  birth_year_to int,
  color varchar(7) not null default '#6366f1',
  sort_order int not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists idx_club_categories_club
  on public.club_categories(club_id, sort_order);

-- Explicit category membership (auto-assigned + manual overrides)
create table if not exists public.category_members (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.club_categories(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  manual_override boolean not null default false,
  excluded boolean not null default false,
  created_at timestamptz not null default now(),
  unique (category_id, user_id)
);

create index if not exists idx_category_members_category
  on public.category_members(category_id);

create index if not exists idx_category_members_user
  on public.category_members(user_id);

-- Event ↔ category link
create table if not exists public.club_event_categories (
  event_id bigint not null references public.club_events(id) on delete cascade,
  category_id bigint not null references public.club_categories(id) on delete cascade,
  primary key (event_id, category_id)
);

-- Explicit event participants (manual add/exclude beyond categories)
create table if not exists public.club_event_participants (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.club_events(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  added_manually boolean not null default false,
  excluded boolean not null default false,
  created_at timestamptz not null default now(),
  unique (event_id, user_id)
);

create index if not exists idx_event_participants_event
  on public.club_event_participants(event_id);

-- dateBirth column on users (already added manually in Supabase, this is idempotent)
alter table public.users
  add column if not exists "dateBirth" date;
